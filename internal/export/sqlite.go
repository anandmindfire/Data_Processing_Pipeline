package export

import (
	"fmt"
	"io"
	"strings"

	"github.com/anandmindfire/data-processing-pipeline/internal/models"
	"github.com/anandmindfire/data-processing-pipeline/internal/validation"
)

// writeSQLite generates standard SQLite DDL and transactional INSERT statements.
func writeSQLite(w io.Writer, records []models.Record) error {
	if len(records) == 0 {
		return nil
	}

	headers := extractHeaders(records)
	var sb strings.Builder

	sb.WriteString("-- SQLite DDL & Data Dump generated by Pipeline\n")
	sb.WriteString("BEGIN TRANSACTION;\n")
	sb.WriteString("CREATE TABLE IF NOT EXISTS records (\n")
	sb.WriteString("    _row_id INTEGER PRIMARY KEY AUTOINCREMENT,\n")

	for i, h := range headers {
		colType := inferColumnType(h, records)
		sb.WriteString(fmt.Sprintf("    %q %s", h, colType))
		if i < len(headers)-1 {
			sb.WriteString(",\n")
		} else {
			sb.WriteString("\n")
		}
	}
	sb.WriteString(");\n\n")

	for _, rec := range records {
		var cols []string
		var vals []string
		for _, h := range headers {
			cols = append(cols, fmt.Sprintf("%q", h))
			val := rec[h]
			if val == nil {
				vals = append(vals, "NULL")
			} else if s, isStr := val.(string); isStr {
				escaped := strings.ReplaceAll(s, "'", "''")
				vals = append(vals, fmt.Sprintf("'%s'", escaped))
			} else if b, isBool := val.(bool); isBool {
				if b {
					vals = append(vals, "1")
				} else {
					vals = append(vals, "0")
				}
			} else if _, isNum := validation.ParseNumber(val); isNum {
				vals = append(vals, fmt.Sprint(val))
			} else {
				escaped := strings.ReplaceAll(fmt.Sprint(val), "'", "''")
				vals = append(vals, fmt.Sprintf("'%s'", escaped))
			}
		}
		sb.WriteString(fmt.Sprintf("INSERT INTO records (%s) VALUES (%s);\n",
			strings.Join(cols, ", "),
			strings.Join(vals, ", ")))
	}

	sb.WriteString("COMMIT;\n")

	_, err := io.WriteString(w, sb.String())
	return err
}

func inferColumnType(col string, records []models.Record) string {
	for _, r := range records {
		val := r[col]
		if val == nil {
			continue
		}
		if _, isNum := validation.ParseNumber(val); !isNum {
			return "TEXT"
		}
	}
	return "NUMERIC"
}
